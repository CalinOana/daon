CREATE TABLE flight (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        departure_airport_code VARCHAR(10) NOT NULL,
                        departure_city VARCHAR(100) NOT NULL,
                        arrival_airport_code VARCHAR(10) NOT NULL,
                        arrival_city VARCHAR(100) NOT NULL,
                        departure_at TIMESTAMP WITH TIME ZONE NOT NULL,
                        total_seats INTEGER NOT NULL CHECK (total_seats > 0),
                        remaining_seats INTEGER NOT NULL CHECK (remaining_seats >= 0 AND remaining_seats <= total_seats),
                        status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'DEPARTED', 'CANCELLED')),
                        version BIGINT NOT NULL DEFAULT 0,
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE booking (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         flight_id BIGINT NOT NULL,
                         passenger_name VARCHAR(150) NOT NULL,
                         passenger_email VARCHAR(255) NOT NULL,
                         status VARCHAR(20) NOT NULL CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
                         expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                         confirmed_at TIMESTAMP WITH TIME ZONE NULL,
                         cancelled_at TIMESTAMP WITH TIME ZONE NULL,
                         version BIGINT NOT NULL DEFAULT 0,
                         created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         CONSTRAINT fk_booking_flight FOREIGN KEY (flight_id) REFERENCES flight(id)
);